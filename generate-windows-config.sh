#!/bin/bash
# Generate Windows-compatible kanata config for GlazeWM
# This script converts Meta (M-) bindings to Alt (A-) bindings for Windows

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INPUT="${SCRIPT_DIR}/kanata.kbd"
OUTPUT="${SCRIPT_DIR}/kanata-windows.kbd"

if [ ! -f "$INPUT" ]; then
    echo "Error: Source config not found at $INPUT"
    exit 1
fi

echo "Generating Windows config from $INPUT..."

# Replace Meta bindings with Alt bindings
# This converts window manager navigation from Meta (Linux) to Alt (Windows/GlazeWM)
sed 's/M-/A-/g' "$INPUT" > "$OUTPUT"

# Add a header comment to the generated file
sed -i '1i;; AUTO-GENERATED CONFIG FOR WINDOWS/GLAZEWM' "$OUTPUT"
sed -i '2i;; Generated from kanata.kbd by generate-windows-config.sh' "$OUTPUT"
sed -i '3i;; DO NOT EDIT THIS FILE DIRECTLY - Edit kanata.kbd and regenerate' "$OUTPUT"
sed -i '4i' "$OUTPUT"

echo "✓ Windows config generated: $OUTPUT"
echo ""
echo "Changes made:"
echo "  - All M- (Meta) bindings → A- (Alt) bindings"
echo ""
echo "Usage:"
echo "  Linux:   Use kanata.kbd"
echo "  Windows: Use kanata-windows.kbd"
