#!/usr/bin/env bash
# Generate Windows-compatible kanata config for GlazeWM
# Converts Meta (M-) bindings to Alt (A-) bindings for Windows
#
# Always edit config.kbd (the Linux version) and re-run this script.
# kanata-windows.kbd is overwritten and must not be edited by hand.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INPUT="${SCRIPT_DIR}/config.kbd"
OUTPUT="${SCRIPT_DIR}/kanata-windows.kbd"

if [ ! -f "$INPUT" ]; then
    echo "Error: Source config not found at $INPUT" >&2
    exit 1
fi

echo "Generating Windows config from $INPUT..."

# Replace Meta bindings with Alt bindings
# This converts window manager navigation from Meta (Linux) to Alt (Windows/GlazeWM)
# Bindings that use Meta *and* Alt (e.g. M-A-spc) are left alone: turning them
# into A-A- would be invalid, and Windows kanata understands M- too.
{
    echo ';; AUTO-GENERATED CONFIG FOR WINDOWS/GLAZEWM'
    echo ';; Generated from config.kbd by generate-windows-config.sh'
    echo ';; DO NOT EDIT THIS FILE DIRECTLY - Edit config.kbd and regenerate'
    echo
    sed -e 's/M-A-/@@KEEP@@/g' -e 's/M-/A-/g' -e 's/@@KEEP@@/M-A-/g' "$INPUT"
} > "$OUTPUT"

echo "✓ Windows config generated: $OUTPUT"
echo ""
echo "Changes made:"
echo "  - All M- (Meta) bindings → A- (Alt) bindings"
echo ""
echo "Usage:"
echo "  Linux:   ~/.config/kanata/config.kbd"
echo "  Windows: kanata-windows.kbd"
